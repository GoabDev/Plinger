import React from "react";
import { createRoot } from "react-dom/client";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import AdminReferrals from "../../app/dashboard/referrals-view";
import Earnings from "../../app/dashboard/wave-earnings-view";
import ScouterReferrals from "../../app/scouter/referrals-view";
import ReferralLogin from "../../app/scouter/login/referral-form";
import "../../app/globals.css";
const mode = new URLSearchParams(location.search).get("view");
const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
createRoot(document.getElementById("root")!).render(<QueryClientProvider client={client}><main style={{ maxWidth: 1200, margin: "0 auto", padding: 24 }}>{mode === "earnings" ? <Earnings totalScouters={2} /> : mode === "self" ? <ScouterReferrals /> : mode === "login" ? <ReferralLogin initialRef="" preview={null} /> : <AdminReferrals />}</main></QueryClientProvider>);
